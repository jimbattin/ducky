// Prints docs/MIDI.md (markdown) from the link's protocol tables (daisy/src/link.h kCommands, kResults), the parameter
// table (daisy/src/params.h), the preset store's constants (daisy/src/preset.h) and the firmware image's
// (daisy/src/fw_image.h): `make midi-doc`.
#include <cstdio>
#include <cstring>

#include "fw_image.h"
#include "link.h"
#include "midi.h"
#include "params.h"
#include "preset.h"

using namespace dklink;

namespace {

// A choice's labels with their indexes: "0 A, 1 B, 2 C" from the unit "A,B,C".
void printChoices(const char* unit) {
    int index = 0;
    for (const char* s = unit; *s;) {
        const char* e = std::strchr(s, ',');
        const int len = e ? int(e - s) : int(std::strlen(s));
        std::printf("%s%d %.*s", index > 0 ? ", " : "", index, len, s);
        ++index;
        s += len + (e ? 1 : 0);
    }
}

}  // namespace

int main() {
    std::printf("<!-- Generated by `make midi-doc` (tools/gen_midi_doc.cpp) from daisy/src/link.h and "
                "daisy/src/params.h. Do not edit. -->\n");
    std::printf("# Ducky: MIDI implementation\n\n");
    std::printf("Ducky talks to a host over the Seed's USB MIDI port with SysEx, and takes two Control Changes: CC %u "
                "(Expression) moves the EXP control and CC %u selects a preset (Controls). It plays no notes, follows "
                "no clock and never sends CC. The protocol table in `daisy/src/link.h` is the single source of truth; "
                "this file is generated from it. `bun tools/pedal.ts` is the command-line client (`editor/src/link/` "
                "holds the protocol code it shares with the editor).\n\n",
                unsigned(dkmidi::kExpressionCc), unsigned(dkmidi::kPresetCc));

    std::printf("## Framing\n\n");
    std::printf("- Every message except the Identity pair is `F0 %02X %02X %02X <cmd> <payload> F7`: manufacturer "
                "`%02X` (non-commercial), device `%02X`, protocol version `%02X`. SysEx for other devices and other "
                "versions is ignored.\n",
                kManufacturer, kDevice, kVersion, kManufacturer, kDevice, kVersion);
    std::printf("- Integers travel as 7-bit bytes (septets), most significant first: u14 is 2 bytes, u21 3, u28 4, "
                "u32 5 (the top septet holds bits 28-31).\n");
    std::printf("- Binary data travels as Pack7: each group of up to 7 bytes becomes one header byte followed by the "
                "low 7 bits of each byte; bit i of the header is the most significant bit of the group's byte i. "
                "n bytes pack into n + ceil(n/7). Example: `80 01 FF 7F 00 81 42 C3` packs to "
                "`25 00 01 7F 7F 00 01 42 01 43`.\n");
    std::printf("- The CRC is CRC-32 (IEEE 802.3 / zlib: reflected polynomial EDB88320, initial and final XOR "
                "FFFFFFFF), the same as the model and preset binaries'.\n");
    std::printf("- Limits: an UPLOAD CHUNK carries at most %zu bytes (%zu packed), so the longest host -> pedal "
                "message is %zu bytes; pedal -> host payloads are at most %zu bytes (a LOG line at most %zu, each "
                "SLOT name at most %zu).\n",
                kChunkBytes, Packed7Size(kChunkBytes), kMaxHostFrame, kMaxPayload, kMaxLog, kMaxName);
    std::printf("- The pedal handles one request at a time: send the next request after the previous one's RESULT. "
                "Slot numbers are 0-7 on the wire (the pedal's log and `tools/pedal.ts` count 1-8).\n\n");

    std::printf("## Commands\n\n");
    std::printf("|Direction|Command|Payload|Effect|\n|---|---|---|---|\n");
    for (const CommandDoc& c : kCommands) {
        const char* dir = c.dir == Dir::kToPedal ? "host to pedal" : "pedal to host";
        if (c.code == 0)
            std::printf("|%s|%s|%s|%s|\n", dir, c.name, c.payload, c.effect);
        else
            std::printf("|%s|`%02X` %s|%s|%s|\n", dir, c.code, c.name, c.payload, c.effect);
    }
    std::printf("\n");

    std::printf("## Results\n\n");
    std::printf("RESULT's value: the next expected offset for UPLOAD BEGIN and CHUNK and FIRMWARE BEGIN and CHUNK; for "
                "READ the next offset; for COMMIT the flash time in ms on ok, the slot status on `invalid`, else 0; "
                "for FIRMWARE COMMIT the flash time in ms on ok, the Firmware check on `invalid`, else 0; for ERASE, "
                "RENAME, SWAP, GATE, MORPH and SAVE the flash time in ms on ok, else 0; 8 for LIST; the parameter "
                "count for DUMP; the code taken for SET; 0 for WATCH, GATE TRY, ASSIGN and EXP CHANNEL. A LIST, "
                "WATCH, COMMIT, FIRMWARE COMMIT, DUMP or SAVE with a payload of the wrong length answers "
                "`bad-request`.\n\n");
    std::printf("|Code|Name|Meaning|\n|---|---|---|\n");
    for (const ResultDoc& r : kResults) std::printf("|%d|%s|%s|\n", int(r.code), r.name, r.meaning);
    std::printf("\n");

    std::printf("## Slot status\n\n");
    std::printf("SLOT's status byte and an `invalid` COMMIT's value: the slot parser's verdict (daisy/src/preset.h, "
                "docs/FIRMWARE.md \"Preset store\").\n\n");
    std::printf("|Value|Name|\n|---|---|\n");
    for (int s = 0; s <= int(dkpreset::Status::kMorph); ++s)
        std::printf("|%d|%s|\n", s, dkpreset::StatusName(dkpreset::Status(s)));
    std::printf("\n");

    std::printf("## Parameters\n\n");
    std::printf("The table DUMP sends (daisy/src/params.h); ids are append-only. A continuous parameter's value is "
                "`min * (max / min) ^ (code / %u)` for a log one, and a linear one's is "
                "`min + (max - min) * code / %u`; a choice's code is its index.\n\n",
                unsigned(dkparam::kCodeMax), unsigned(dkparam::kCodeMax));
    std::printf("|Id|Name|Label|Taper|Range|Off end|Default code|Group|\n"
                "|---|---|---|---|---|---|---|---|\n");
    for (const dkparam::ParamDef& d : dkparam::kParams) {
        const bool choice = d.taper == dkparam::Taper::kChoice;
        std::printf("|%d|`%s`|%s|%s|", d.id, d.name, d.label,
                    choice ? "choice" : d.taper == dkparam::Taper::kLinear ? "linear" : "log");
        if (choice)
            printChoices(d.unit);
        else
            std::printf("%g to %g %s", double(d.min), double(d.max), d.unit);
        std::printf("|%s|%u|%s|\n",
                    d.off == dkparam::OffEnd::kMin ? "min" : d.off == dkparam::OffEnd::kMax ? "max" : "-",
                    unsigned(dkparam::ToCode(d, d.def)), d.group);
    }
    std::printf("\n");

    std::printf("## Controls\n\n");
    std::printf("- Controls 0-7 are Knob 3, Knob 4, Knob 5, Knob 6, SW1, SW2, SW3 and EXP, the expression pedal "
                "(`k3`-`k6`, `sw1`-`sw3`, `exp` in the log and `tools/pedal.ts`). Each drives one parameter or none "
                "(7F); a parameter may be on several controls or on none. Knobs 1 and 2 are fixed: the input trim and "
                "the output volume.\n");
    std::printf("- A knob takes any parameter. A choice parameter on a knob splits its travel evenly between its "
                "values, and changes %g of a step past each boundary, so a knob resting on one does not flip.\n",
                double(dkparam::kChoiceHysteresis));
    std::printf("- A switch takes choice parameters only. A three-value parameter's index is the position: 0 down, 1 "
                "middle, 2 up. A two-value one is 0 in the middle and 1 up or down.\n");
    std::printf("- EXP takes any parameter, as a knob does. Its position is the last CC %u (Expression) value / 127 "
                "received on the Seed's USB MIDI port, e.g. from a USB-MIDI expression pedal acting as USB host, on "
                "the channel EXP CHANNEL sets (any channel unless set). Each CC writes the parameter; until the first "
                "one after power-up the parameter keeps its saved value.\n",
                unsigned(dkmidi::kExpressionCc));
    std::printf("- Presets: CC %u with value 0-7 on EXP CHANNEL's channel switches to slot 1-8, as FS2 does; a value "
                "past the slots, or an empty or broken slot, is ignored.\n",
                unsigned(dkmidi::kPresetCc));
    std::printf("- Pickup: a control writes its parameter when it moves. SET, and ASSIGN of a control, hold the "
                "control: the parameter keeps its value until a knob or EXP has moved more than %g %% of its travel "
                "from where it was, or a switch changes position. When a parameter is on several controls, the one "
                "moved last has it and the others are held. VALUES' held bits show the held controls.\n",
                double(dkparam::kPickup) * 100.0);
    std::printf("- At power-up every parameter on a knob or switch takes its control's position (with several "
                "controls on it, one of theirs); one on EXP or on no control takes its saved value.\n");
    std::printf("- ASSIGN and SET act at once but are lost at power-off. SAVE writes the assignments, the expression "
                "channel and the values to the settings record (docs/FIRMWARE.md \"Settings record\"); with no "
                "record the pedal starts in the factory layout with every parameter at its default. The settings are "
                "global: presets hold neither assignments nor values.\n");
    std::printf("- Factory layout (params.h kFactoryAssign):");
    for (int c = 0; c < dkparam::kControlSlots; ++c) {
        const uint8_t id = dkparam::kFactoryAssign[c];
        const char* name = id == dkparam::kNoParam ? "none" : dkparam::kParams[id].name;
        std::printf("%s `%s` `%s`", c == 0 ? "" : ",", dkparam::kControlNames[c], name);
    }
    std::printf(".\n\n");

    std::printf("## Upload\n\n");
    std::printf("An image is a complete format-3 preset slot (docs/FIRMWARE.md \"Preset store\"): %zu bytes without "
                "an IR, %zu with one; %zu more with a morph block, and %zu more for each of its trained path's "
                "waypoints (0-%d), %zu at most. UPLOAD BEGIN takes these sizes only. An upload replaces the whole "
                "slot, so one without a morph block over a preset drops the block and the waypoints it had; MORPH "
                "sets or removes the block of a stored preset, and removes its waypoints.\n\n",
                dkpreset::kSizeNoIr, dkpreset::kSizeWithIr, dkmorph::kBlockBytes, dkmorph::kWaypointBytes,
                dkmorph::kMaxWaypoints, dkpreset::kSizeMax);
    std::printf("1. UPLOAD BEGIN `<slot> <size>`; RESULT ok, value 0. A BEGIN discards any earlier upload. Resend "
                "it when no RESULT arrives.\n");
    std::printf("2. UPLOAD CHUNK for each run of up to %zu bytes, in order: `<offset> <crc> <data>`. RESULT ok "
                "gives the next offset. With no RESULT (1 s) or `crc`, resend the same chunk: a chunk at or below "
                "the next offset is accepted again, so resending is safe. `offset` (the chunk starts past the next "
                "expected offset) gives the offset to continue from. `tools/pedal.ts` gives up after 5 retries of "
                "one chunk.\n",
                kChunkBytes);
    std::printf("3. UPLOAD COMMIT: the pedal parses the image as a preset, erases the slot's 64 KB block, writes "
                "the image and reads it back. The upload is cleared whatever the outcome, so COMMIT is not resent: "
                "with no RESULT (allow 10 s), LIST shows whether the slot holds the new preset.\n\n");

    std::printf("## Firmware update\n\n");
    std::printf("The image is the `.bin` of an `APP=xfade` (the default) or `APP=weight` build "
                "(`daisy/build/hothouse-*/ducky_*.bin`), %u-%u bytes. The Daisy bootloader copies it from QSPI "
                "0x%08X into SRAM 0x%08X at boot, so the running firmware never executes from the flash it "
                "rewrites. It starts with the vector table; at 0x%X it carries a %u-byte tag: `DKFW` (0x%08X "
                "little-endian), version %u, the board (the Identity Reply's), the Identity Reply's flags, each a "
                "little-endian u32 (`daisy/src/fw_image.h`). Images without the tag (the `APP=bench` and "
                "`APP=latency` builds, and builds made before firmware updates) are refused: every image that "
                "is accepted can itself be updated this way. `tools/pedal.ts firmware FILE.bin` and the editor's "
                "Firmware button run these steps.\n\n",
                unsigned(dkfwimg::kMinImageBytes), unsigned(dkfwimg::kMaxImageBytes),
                unsigned(dkpreset::kQspiBase + dkfwimg::kQspiOffset), unsigned(dkfwimg::kSramBase),
                unsigned(dkfwimg::kTagOffset), unsigned(dkfwimg::kTagBytes), unsigned(dkfwimg::kTagMagic),
                unsigned(dkfwimg::kTagVersion));
    std::printf("1. FIRMWARE BEGIN `<size> <crc>`, the CRC-32 of the whole image; RESULT ok, value 0. A BEGIN "
                "discards any earlier image.\n");
    std::printf("2. FIRMWARE CHUNK for each run of up to %zu bytes, as UPLOAD CHUNK (Upload), with the same "
                "resends.\n",
                kChunkBytes);
    std::printf("3. FIRMWARE COMMIT (allow 30 s): the pedal checks the image (Firmware checks), erases the 64 KB "
                "blocks it covers from 0x%08X, writes it and reads it back, then answers RESULT ok with the flash "
                "time; audio keeps running meanwhile. Resend COMMIT only on `flash`, which keeps the staged image. "
                "The pedal then logs `firmware restart` and restarts through the bootloader into the new image "
                "(audio stops for a few seconds); it comes back on USB with the new Identity, its presets and "
                "settings untouched.\n\n",
                unsigned(dkpreset::kQspiBase + dkfwimg::kQspiOffset));
    std::printf("## Firmware checks\n\n");
    std::printf("An `invalid` FIRMWARE COMMIT's value, in the order the pedal checks: the image's CRC-32 is "
                "BEGIN's; its initial stack pointer lies in DTCM and its reset vector is a Thumb address inside the "
                "image as loaded in SRAM; the tag's magic and version; the tag's board is the pedal's. Nothing is "
                "erased when a check fails, and the staged image is cleared.\n\n");
    std::printf("|Value|Name|\n|---|---|\n");
    for (int c = 0; c <= int(dkfwimg::Check::kBoard); ++c)
        std::printf("|%d|%s|\n", c, dkfwimg::CheckName(dkfwimg::Check(c)));
    std::printf("\n");

    std::printf("## Slot changes and playback\n\n");
    std::printf("- Audio keeps running through every slot operation: the audio callback reads nothing from QSPI. "
                "Each flash operation blocks the pedal's main loop for its erase and write (hundreds of ms): LOG "
                "lines, STATUS and footswitch preset switches wait, then catch up.\n");
    std::printf("- Every successful slot change logs a line (`upload slot N \"NAME\" T ms`, `erase slot N T ms`, "
                "`rename slot N \"NAME\" T ms`, `swap slots A B T ms`, `gate slot N on|off T ms`, "
                "`morph slot N -> M|off T ms`), then the `slots` line; a failed write logs `slot write failed N`.\n");
    std::printf("- An upload into the playing slot reloads it at once, with the usual preset-switch fade. An "
                "upload while the pedal plays dry (no valid slot) starts playing the new slot.\n");
    std::printf("- Erasing the playing slot switches to the next filled slot (LED2 blinks its number), or to dry "
                "when none is left. A rename leaves the audio untouched.\n");
    std::printf("- GATE on the playing slot changes the running gate at once, without a reload or a fade. GATE TRY "
                "changes only the running gate, so an editor can audition settings while a slider moves; the next "
                "preset load (a footswitch switch, an upload, an erase) or GATE undoes it.\n");
    std::printf("- MORPH on the playing slot reloads it, with the preset-switch fade. A playing preset whose morph "
                "target is uploaded over, erased or swapped reloads too: it goes on morphing with whichever slot "
                "holds the model its block was fitted to, and plays its own model alone when none does (the log's "
                "`morph missing slot N`). An uploaded preset's morph block is resolved the same way, so it may "
                "arrive before its target.\n");
    std::printf("- SWAP moves presets, not playback: the playing preset keeps playing under its new slot number, "
                "which the pedal remembers (as after a footswitch switch, once it has settled for 2 s). SWAP writes "
                "slot a, then slot b: a power loss between the two writes leaves both slots holding b's old preset, "
                "or both empty when b was empty (a's preset is lost); LIST shows it, and an upload restores it.\n");
    return 0;
}
