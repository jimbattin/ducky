// The startup every image shares, and the build id. libDaisy-dependent.
//
// MPU: ST's background MPU region for the STM32H7 (AN4838; STM32CubeMX's default): no access, execute-never and
// strongly ordered over the external-memory window 0x60000000-0xDFFFFFFF (subregions 3-6 of a 4 GB region).
// The Cortex-M7 reads Normal memory speculatively, through whatever value a register holds (ES0392 2.1.2);
// libDaisy leaves this window on the default map, which includes the 8 MB memory-mapped QSPI region.
// A repeated read of its last byte, 0x907FFFFF, stalls the AXI bus (ES0392 2.7.5), and no interrupt can
// break the stall. Any register holding an emulator counter or address can pass through that value. A no-access
// region is never read speculatively; a real access raises MemManage. Region 0 is that background region (it replaces
// libDaisy's region 0); libDaisy's three regions (System::ConfigureMpu) are rewritten here as regions 1-3 with the
// same attributes. Higher region numbers win where regions overlap.
// The image runs from SRAM (BOOT_SRAM). Region 4 makes the preset store (preset.h, the 1 MB at 0x90400000) readable,
// privileged read-only, write-through cached and execute-never; the rest of the QSPI window, 0x907FFFFF included,
// stays no-access.
// libDaisy's System::Init enables the caches before this runs, and memory attributes must not change under cached
// lines: the caches are cleaned, invalidated and disabled around the change, then re-enabled as they were.
#pragma once

#include <cstddef>

#include "board.h"
#include "daisy_seed.h"

extern "C" const char kBuildId[];  // $(BUILD_DIR)/build_id.c, generated by daisy/Makefile

namespace dkfw {

using ::kBuildId;

// FZ: denormals flush to zero.
inline void EnableFlushToZero() { __set_FPSCR(__get_FPSCR() | (1u << 24)); }

inline void ConfigureMpu() {
    const bool dcache = (SCB->CCR & SCB_CCR_DC_Msk) != 0, icache = (SCB->CCR & SCB_CCR_IC_Msk) != 0;
    if (icache) SCB_DisableICache();
    if (dcache) SCB_DisableDCache();  // cleans and invalidates
    HAL_MPU_Disable();
    MPU_Region_InitTypeDef r{};
    r.Enable = MPU_REGION_ENABLE;

    // The background region (replaces libDaisy's region 0).
    r.Number = MPU_REGION_NUMBER0;
    r.BaseAddress = 0x00000000;
    r.Size = MPU_REGION_SIZE_4GB;
    r.SubRegionDisable = 0x87;   // keep the default map for 0x00000000-0x5FFFFFFF and 0xE0000000-0xFFFFFFFF
    r.AccessPermission = MPU_REGION_NO_ACCESS;
    r.DisableExec = MPU_INSTRUCTION_ACCESS_DISABLE;
    r.TypeExtField = MPU_TEX_LEVEL0;
    r.IsCacheable = MPU_ACCESS_NOT_CACHEABLE;
    r.IsBufferable = MPU_ACCESS_NOT_BUFFERABLE;
    r.IsShareable = MPU_ACCESS_SHAREABLE;
    HAL_MPU_ConfigRegion(&r);

    r.SubRegionDisable = 0x00;
    r.AccessPermission = MPU_REGION_FULL_ACCESS;
    r.DisableExec = MPU_INSTRUCTION_ACCESS_ENABLE;

    // libDaisy's region 0 as region 1: D2 SRAM1, the DMA buffers, uncached.
    r.Number = MPU_REGION_NUMBER1;
    r.BaseAddress = 0x30000000;
    r.Size = MPU_REGION_SIZE_32KB;
    r.TypeExtField = MPU_TEX_LEVEL1;
    r.IsCacheable = MPU_ACCESS_NOT_CACHEABLE;
    r.IsBufferable = MPU_ACCESS_NOT_BUFFERABLE;
    r.IsShareable = MPU_ACCESS_SHAREABLE;
    HAL_MPU_ConfigRegion(&r);

    // libDaisy's region 1 as region 2: SDRAM, write-back cached.
    r.Number = MPU_REGION_NUMBER2;
    r.BaseAddress = 0xC0000000;
    r.Size = MPU_REGION_SIZE_64MB;
    r.TypeExtField = MPU_TEX_LEVEL0;
    r.IsCacheable = MPU_ACCESS_CACHEABLE;
    r.IsBufferable = MPU_ACCESS_BUFFERABLE;
    r.IsShareable = MPU_ACCESS_NOT_SHAREABLE;
    HAL_MPU_ConfigRegion(&r);

    // libDaisy's region 2 as region 3: backup SRAM, uncached (libDaisy's boot_info).
    r.Number = MPU_REGION_NUMBER3;
    r.BaseAddress = 0x38800000;
    r.Size = MPU_REGION_SIZE_4KB;
    r.TypeExtField = MPU_TEX_LEVEL1;
    r.IsCacheable = MPU_ACCESS_NOT_CACHEABLE;
    r.IsBufferable = MPU_ACCESS_NOT_BUFFERABLE;
    r.IsShareable = MPU_ACCESS_SHAREABLE;
    HAL_MPU_ConfigRegion(&r);

    // Region 4: the preset store, 0x90400000-0x904FFFFF of the memory-mapped flash (preset.h kMpuBytes).
    r.Number = MPU_REGION_NUMBER4;
    r.BaseAddress = 0x90400000;
    r.Size = MPU_REGION_SIZE_1MB;
    r.AccessPermission = MPU_REGION_PRIV_RO;
    r.DisableExec = MPU_INSTRUCTION_ACCESS_DISABLE;
    r.TypeExtField = MPU_TEX_LEVEL0;
    r.IsCacheable = MPU_ACCESS_CACHEABLE;
    r.IsBufferable = MPU_ACCESS_NOT_BUFFERABLE;
    r.IsShareable = MPU_ACCESS_NOT_SHAREABLE;
    HAL_MPU_ConfigRegion(&r);

    HAL_MPU_Enable(MPU_PRIVILEGED_DEFAULT);
    if (dcache) SCB_EnableDCache();  // invalidates first
    if (icache) SCB_EnableICache();
}

// Every image's first call: FZ, the board (480 MHz, SDRAM) at rate and blockSize, the MPU.
inline void Start(dkboard::Board& hw, size_t blockSize, daisy::SaiHandle::Config::SampleRate rate) {
    EnableFlushToZero();
    hw.Init(blockSize, rate);
    ConfigureMpu();
}

}  // namespace dkfw
